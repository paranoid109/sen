"""SentinelX Immutable Contract Models (Pydantic v2).

These models are the exact Python twins of the JSON Schemas in `contracts/`.
All cross-module and API communication across the platform conforms strictly to these definitions.
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Any
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field


class SeverityLevel(str, Enum):
    """Standard 4-tier severity levels."""

    CRITICAL = "critical"
    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class AlertStatus(str, Enum):
    """Triage lifecycle states for alerts."""

    NEW = "NEW"
    INVESTIGATING = "INVESTIGATING"
    RESOLVED = "RESOLVED"
    FALSE_POSITIVE = "FALSE_POSITIVE"


class IncidentStatus(str, Enum):
    """Lifecycle states for correlated incidents."""

    OPEN = "OPEN"
    INVESTIGATING = "INVESTIGATING"
    RESOLVED = "RESOLVED"
    CLOSED = "CLOSED"


class ActionStatus(str, Enum):
    """Execution lifecycle states for remediation/notification actions."""

    PENDING = "PENDING"
    EXECUTING = "EXECUTING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class ActionType(str, Enum):
    """Supported classifications for remediation or notification actions."""

    WEBHOOK_NOTIFICATION = "webhook_notification"
    BLOCK_IP = "block_ip"
    ISOLATE_HOST = "isolate_host"
    DISABLE_USER = "disable_user"
    CUSTOM = "custom"


class EventContract(BaseModel):
    """Normalized security telemetry event contract (M3)."""

    model_config = ConfigDict(extra="forbid")

    event_id: UUID = Field(description="Unique UUIDv4 identifier of the event")
    source_ip: str = Field(description="Source IP address or hostname of the traffic/actor")
    destination_ip: str | None = Field(
        default=None, description="Destination IP address of monitored target"
    )
    destination_port: int | None = Field(
        default=None, ge=1, le=65535, description="Destination TCP/UDP port"
    )
    source_port: int | None = Field(default=None, ge=1, le=65535, description="Source TCP/UDP port")
    event_type: str = Field(description="Normalized event classification")
    target_host: str | None = Field(
        default=None, description="Target hostname from log line or ingestion request"
    )
    target_asset_id: str | None = Field(
        default=None, description="Resolved CMDB monitored asset UUID"
    )
    event_time: datetime = Field(description="UTC timestamp when the event occurred at source")
    ingest_time: datetime = Field(description="UTC timestamp when SentinelX ingested the event")
    raw_payload: str | None = Field(default=None, description="Original raw log line or payload")
    details: dict[str, Any] = Field(
        default_factory=dict, description="Arbitrary key-value metadata extracted by log parsers"
    )


class FindingContract(BaseModel):
    """Standard finding artifact emitted by standalone capability modules (X1-X13)."""

    model_config = ConfigDict(extra="forbid")

    finding_id: UUID = Field(description="Unique UUIDv4 identifier of the finding")
    tool_name: str = Field(description="Name of the capability tool producing the finding")
    rule_id: str = Field(description="Identifier of the rule or signature triggered")
    severity: SeverityLevel = Field(description="Finding severity classification")
    target: str = Field(description="Target URI, IP, or hostname investigated")
    description: str = Field(description="Summary of the security finding")
    evidence: dict[str, Any] | str | None = Field(
        default=None, description="Extracted evidence payload or metadata"
    )
    timestamp: datetime = Field(description="UTC timestamp when the finding was generated")
    mitre_attack_id: str | None = Field(
        default=None, description="Associated MITRE ATT&CK technique ID"
    )


class AlertContract(BaseModel):
    """Curated security alert generated by Detection Engine (M4) and managed by Alert Service (M5)."""

    model_config = ConfigDict(extra="forbid")

    alert_id: UUID = Field(description="Unique UUIDv4 identifier of the alert")
    rule_id: str = Field(description="Identifier of the triggered detection rule")
    rule_name: str = Field(description="Human-readable detection rule name")
    severity: SeverityLevel = Field(description="Alert severity rating")
    status: AlertStatus = Field(description="Alert triage state")
    mitre_attack_id: str | None = Field(default=None, description="MITRE ATT&CK technique ID")
    source_ip: str = Field(description="Attacker/source IP address")
    target_asset_id: str | None = Field(
        default=None, description="UUID of the victim/monitored CMDB asset"
    )
    target_host: str | None = Field(default=None, description="Victim hostname or IP identifier")
    dedup_key: str = Field(min_length=64, max_length=64, description="SHA-256 deduplication hash")
    occurrence_count: int = Field(ge=1, description="Total number of aggregated event occurrences")
    first_seen: datetime = Field(
        description="UTC timestamp of the earliest event matching this alert"
    )
    last_seen: datetime = Field(
        description="UTC timestamp of the most recent event matching this alert"
    )
    evidence: list[str] = Field(
        default_factory=list,
        max_length=100,
        description="List of supporting event UUIDs capped at 100",
    )
    created_at: datetime = Field(description="UTC creation timestamp")
    updated_at: datetime = Field(description="UTC last updated timestamp")


class TimelineItem(BaseModel):
    """Chronological timeline entry associated with an incident."""

    model_config = ConfigDict(extra="forbid")

    timestamp: datetime = Field(description="UTC timestamp of timeline event")
    event_type: str = Field(description="Classification of activity")
    description: str = Field(description="Details of activity")
    source: str = Field(description="Actor, system, or module reporting the item")


class IncidentContract(BaseModel):
    """Correlated security incident aggregating alerts with closed-form risk score (M6)."""

    model_config = ConfigDict(extra="forbid")

    incident_id: UUID = Field(description="Unique UUIDv4 identifier of the incident")
    title: str = Field(description="Incident title summarizing the threat")
    description: str | None = Field(
        default=None, description="Detailed incident narrative and context"
    )
    severity: SeverityLevel = Field(description="Overall incident severity rating")
    status: IncidentStatus = Field(description="Lifecycle state of the incident")
    risk_score: int = Field(ge=0, le=100, description="Closed-form bounded risk score (0 to 100)")
    target_asset_id: str | None = Field(
        default=None, description="UUID of the monitored victim CMDB asset"
    )
    target_host: str | None = Field(default=None, description="Victim hostname or IP")
    alert_ids: list[str] = Field(description="List of alert UUIDs correlated under this incident")
    timeline: list[TimelineItem] = Field(
        default_factory=list, description="Chronological audit timeline of incident activity"
    )
    created_at: datetime = Field(description="UTC incident creation timestamp")
    updated_at: datetime = Field(description="UTC last updated timestamp")


class ActionContract(BaseModel):
    """Standard response action contract for notifications and remediation actions (M6/M7, X10)."""

    model_config = ConfigDict(extra="forbid")

    action_id: UUID = Field(description="Unique UUIDv4 identifier of the action")
    action_type: ActionType = Field(
        description="Classification of remediation or notification action"
    )
    incident_id: UUID = Field(description="UUID of the correlated incident triggering this action")
    target: str = Field(description="Target entity for the action")
    parameters: dict[str, Any] = Field(
        default_factory=dict, description="Configuration parameters passed to action handler"
    )
    status: ActionStatus = Field(description="Execution lifecycle state of the action")
    requested_by: str = Field(description="Identifier of actor or system triggering the action")
    requested_at: datetime = Field(description="UTC timestamp when the action was requested")
    executed_at: datetime | None = Field(
        default=None, description="UTC timestamp when action execution completed"
    )
    result: dict[str, Any] | str | None = Field(
        default=None, description="Execution output or error details"
    )
